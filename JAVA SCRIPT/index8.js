//  FOR LOOPS.


// Forward loops
for(let i = 1; i<=5; i++){
    console.log(i);
}

//  Backward loops
for(let m = 5; m>=1;m--){
    console.log(m)
}

// For Odd Numbers.(FORWARD)
for(let n = 1; n<=20; n=n+2){
    console.log(n)
}

//  PRINT ALL EVEN NUMBER (FORWARD).
for(let p = 0; p<=20; p=p+2){
    console.log(p)
}

